// Turns the Orca app themes in scripts/code-themes/ into the Shiki themes the guide tab colours
// diffs with (editor/code-themes.ts). Run after changing one:
//
//   bun scripts/vendor-code-themes.ts
import { readFile, writeFile } from "node:fs/promises";

const SOURCES = [
  { id: "cursor-dark", title: "Cursor Dark", file: "cursor-dark.json" },
  { id: "armada", title: "Armada", file: "armada.json" },
] as const;

type OrcaTheme = {
  base: "dark" | "light";
  tokens: Record<string, string>;
  tokenColors: {
    scope?: string | string[];
    settings: { foreground?: string; fontStyle?: string };
  }[];
};

function isOrcaTheme(value: unknown): value is OrcaTheme {
  if (typeof value !== "object" || value === null) return false;
  if (!("base" in value) || (value.base !== "dark" && value.base !== "light")) return false;
  if (!("tokens" in value) || typeof value.tokens !== "object" || value.tokens === null)
    return false;
  return "tokenColors" in value && Array.isArray(value.tokenColors);
}

const dir = new URL("./code-themes/", import.meta.url);
const themes = await Promise.all(
  SOURCES.map(async ({ id, title, file }) => {
    const t: unknown = JSON.parse(await readFile(new URL(file, dir), "utf8"));
    if (!isOrcaTheme(t)) throw new Error(`${file} is not an Orca app theme`);
    const background = t.tokens["--editor-surface"] ?? t.tokens["--background"];
    const foreground = t.tokens["--foreground"];
    return {
      id,
      title,
      theme: {
        name: id,
        type: t.base,
        colors: { "editor.background": background, "editor.foreground": foreground },
        fg: foreground,
        bg: background,
        settings: [{ settings: { foreground, background } }, ...t.tokenColors],
      },
    };
  }),
);
const out = new URL("../editor/code-themes.ts", import.meta.url);
await writeFile(
  out,
  [
    "// Generated by scripts/vendor-code-themes.ts from scripts/code-themes/. Do not edit.",
    'import type { ShikiTheme } from "./vendor/shiki/shiki.js";',
    "",
    `export const CODE_THEMES = ${JSON.stringify(themes, null, 2)} as const satisfies readonly { id: string; title: string; theme: ShikiTheme }[];`,
    "",
    'export type CodeThemeId = (typeof CODE_THEMES)[number]["id"];',
    "",
  ].join("\n"),
);
console.log(`wrote ${out.pathname}`);
